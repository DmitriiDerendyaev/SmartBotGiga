package ru.smartbot.domain.error;

/**
 * Единый каталог доменных ошибок (AD-20, FR24).
 *
 * <p>Единственный источник кодов для всех модулей: адаптеры маппят внешние
 * ошибки в эти коды, application-api/impl рендерит по ним безопасный текст
 * ({@code SafeErrorMessages}). Состав каталога зафиксирован spine AD-20 —
 * изменение требует amendment spine.
 *
 * <p>Коды не несут внутренних деталей и пригодны для персистентности
 * (хранятся как имя, не ordinal).
 */
public enum ErrorCode {

    /** Некорректный запрос/данные (валидация на входе). */
    VALIDATION,

    /** Callback не прошёл валидацию: подделан, чужой, без inline_message_id. */
    INVALID_CALLBACK,

    /** Истёк TTL запроса/кнопки; ставится только application-impl. */
    EXPIRED,

    /** Пользователь заблокирован; доступ к генерации запрещён. */
    BLOCKED,

    /** Превышен rate limit (частота запросов). */
    RATE_LIMITED,

    /** Исчерпана квота пользователя. */
    QUOTA_EXCEEDED,

    /** Исчерпан бюджет (Phase 7). */
    BUDGET_EXCEEDED,

    /** Таймаут обработки/внешнего вызова. */
    TIMEOUT,

    /** LLM-провайдер недоступен. */
    PROVIDER_UNAVAILABLE,

    /** Ошибка авторизации у внешнего провайдера. */
    AUTH,

    /** Поиск недоступен. */
    SEARCH_UNAVAILABLE,

    /** Не удалось доставить/обновить сообщение (delivery_error_code). */
    DELIVERY_FAILED,

    /** Запрос превышает лимит длины; отказ без обрезки (AD-19). */
    MESSAGE_TOO_LONG,

    /** Обработка прервана рестартом; осиротевший GENERATING → FAILED (AD-15). */
    RESTARTED,

    /** Непредвиденная внутренняя ошибка. */
    INTERNAL
}